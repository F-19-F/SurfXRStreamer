"""Regenerate or verify the embedded, original GLSL shaders; no GPU is used."""
import argparse
from embed_spirv import write_shader_headers
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if the embedded header differs")
    parser.add_argument("--compiler", default="glslangValidator")
    parser.add_argument("--validator", default="spirv-val")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2] / "surfxr"
    arrays = []
    hashes = []
    with tempfile.TemporaryDirectory(prefix="surfxr-foveation-shaders-") as directory:
        # Keep the portable Vulkan 1.0 module free of subgroup capabilities.
        # Callers may opt in to the separate Vulkan 1.1 quad variant only after
        # querying fragment-stage subgroup BASIC/QUAD support on their device.
        variants = (("vert", "vert", "vulkan1.0", []),
                    ("frag", "frag", "vulkan1.0", []),
                    ("quad_frag", "frag", "vulkan1.1", ["-DSURFXR_FOVEATION_QUAD=1"]))
        for name, stage, target, defines in variants:
            source = root / "frame/xr/shaders" / ("foveation." + stage)
            binary = Path(directory) / (name + ".spv")
            subprocess.run([args.compiler, "-V", "--target-env", target, *defines,
                            str(source), "-o", str(binary)], check=True)
            subprocess.run([args.validator, "--target-env", target, str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack("<" + "I" * (len(data) // 4), data)
            lines = [", ".join(f"0x{word:08x}u" for word in words[i:i + 8])
                     for i in range(0, len(words), 8)]
            arrays.append("inline constexpr std::uint32_t foveation_" + name + "_spv[] = {\n    "
                          + ",\n    ".join(lines) + "\n};\n")
            # Include shared source in provenance, as well as in the compiled
            # binary checked against the embedded header.
            sources = source.read_bytes()
            if stage != "vert":
                sources += (root / "frame/xr/shaders" / "foveation_postprocess.glsl").read_bytes()
                sources += (root / "frame/xr/shaders" / "foveation_gamma2.glsl").read_bytes()
                sources += (root / "frame/xr/shaders" / "nv12_sampling.glsl").read_bytes()
            hashes.append(name + ": GLSL " + hashlib.sha256(sources).hexdigest()
                          + ", SPIR-V " + hashlib.sha256(data).hexdigest())
    generated = ("// Generated by scripts/shaders/compile_foveation_shaders.py\n#pragma once\n"
                 "#include <cstdint>\nnamespace surfxr {\n" + "\n".join(arrays) + "} // namespace surfxr\n")
    write_shader_headers(root, "foveation", generated, args.check)
    print("\n".join(hashes))


if __name__ == "__main__":
    main()
