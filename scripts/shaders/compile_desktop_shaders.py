"""Regenerate or verify the original desktop projection shaders; no GPU is used."""
import argparse
from embed_spirv import write_shader_headers
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--compiler", default="glslangValidator")
    parser.add_argument("--validator", default="spirv-val")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2] / "surfxr"
    arrays, hashes = [], []
    with tempfile.TemporaryDirectory(prefix="surfxr-desktop-shaders-") as directory:
        for stage in ("vert", "frag"):
            source = root / "frame/xr/shaders" / ("desktop_mesh." + stage)
            binary = Path(directory) / (stage + ".spv")
            subprocess.run([args.compiler, "-V", "--target-env", "vulkan1.1",
                            str(source), "-o", str(binary)], check=True)
            subprocess.run([args.validator, "--target-env", "vulkan1.1", str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack("<" + "I" * (len(data) // 4), data)
            rows = [", ".join(f"0x{word:08x}u" for word in words[i:i + 8])
                    for i in range(0, len(words), 8)]
            arrays.append("inline constexpr std::uint32_t mesh_" + stage + "_spv[] = {\n    "
                          + ",\n    ".join(rows) + "\n};\n")
            sources = source.read_bytes()
            if stage == "frag":
                sources += (root / "frame/xr/shaders/nv12_sampling.glsl").read_bytes()
            hashes.append(stage + ": GLSL " + hashlib.sha256(sources).hexdigest()
                          + ", SPIR-V " + hashlib.sha256(data).hexdigest())
    generated = ("// Generated by scripts/shaders/compile_desktop_shaders.py\n#pragma once\n"
                 "#include <cstdint>\nnamespace surfxr {\n" + "\n".join(arrays) + "} // namespace surfxr\n")
    write_shader_headers(root, "desktop_mesh", generated, args.check)
    print("\n".join(hashes))



if __name__ == "__main__":
    main()
