"""Build and validate spatial enhancement SPIR-V; no headset or GPU is used."""
import argparse
from embed_spirv import write_shader_headers
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--compiler", default="glslangValidator")
    parser.add_argument("--validator", default="spirv-val")
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[2] / "surfxr"
    arrays = []
    with tempfile.TemporaryDirectory(prefix="surfxr-enhancement-") as directory:
        for stage in ("vert", "frag"):
            source = root / "frame/xr/shaders" / ("image_enhancement." + stage)
            binary = Path(directory) / (stage + ".spv")
            subprocess.run([args.compiler, "-V", "--target-env", "vulkan1.0", str(source), "-o", str(binary)], check=True)
            subprocess.run([args.validator, "--target-env", "vulkan1.0", str(binary)], check=True)
            data = binary.read_bytes()
            words = struct.unpack("<" + "I" * (len(data) // 4), data)
            lines = [", ".join(f"0x{word:08x}u" for word in words[i:i+8]) for i in range(0, len(words), 8)]
            arrays.append("inline constexpr std::uint32_t image_enhancement_" + stage + "_spv[] = {\n    " + ",\n    ".join(lines) + "\n};\n")
            print(stage, "GLSL", hashlib.sha256(source.read_bytes()).hexdigest(), "SPIR-V", hashlib.sha256(data).hexdigest())
    generated = "// Generated by scripts/shaders/compile_image_enhancement_shaders.py\n// SGSR1 BSD-3-Clause attribution: frame/xr/shaders/image_enhancement.LICENSE\n#pragma once\n#include <cstdint>\nnamespace surfxr {\n" + "\n".join(arrays) + "} // namespace surfxr\n"
    write_shader_headers(root, "image_enhancement", generated, args.check)



if __name__ == "__main__":
    main()
